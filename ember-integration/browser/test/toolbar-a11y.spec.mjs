test('forced colors and reduced motion retain visible focus and pressed indication', async ({ page }) => {
  await page.emulateMedia({ forcedColors: 'active', reducedMotion: 'reduce' })
  await mount(page)
  await action(page, 'bold').focus()
  await page.keyboard.press('Space')
  const styles = await action(page, 'bold').evaluate(el => {
    const s = getComputedStyle(el)
    return { outline: s.outlineStyle, width: s.outlineWidth, border: s.borderTopWidth,
      transition: s.transitionDuration, decoration: s.textDecorationLine }
  })
  expect(styles.outline).not.toBe('none')
  expect(styles.width).toBe('3px')
  expect(styles.border).toBe('3px')
  expect(styles.decoration).toContain('underline')
  expect(styles.transition).toBe('0s')
})
