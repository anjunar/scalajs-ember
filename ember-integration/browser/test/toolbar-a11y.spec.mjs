test('link validation retains the dialog and source, then maps both endpoints through background edits', async ({ page }) => {
  await mount(page)
  await link(page)
  await page.getByLabel('Adresse', { exact: true }).fill('javascript:bad')
  await page.getByRole('button', { name: 'Übernehmen' }).click()
  await expect(page.getByRole('alert')).not.toBeEmpty()
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(await page.evaluate(() => window.toolbar.text())).toBe('Hello world')
  await page.getByLabel('Adresse', { exact: true }).focus()
  await page.evaluate(() => window.toolbar.edit())
  await expect(page.getByLabel('Adresse', { exact: true })).toBeFocused()
  await page.getByLabel('Adresse', { exact: true }).fill('/mapped')
  await page.getByLabel('Titel', { exact: true }).fill('Mapped title')
  await page.getByRole('button', { name: 'Übernehmen' }).click()
  await expect(editor(page).locator('a')).toHaveAttribute('href', '/mapped')
  await expect(editor(page).locator('a')).toHaveAttribute('title', 'Mapped title')
  expect(await page.evaluate(() => window.toolbar.text())).toBe('XHello world')
  expect(await page.evaluate(() => window.toolbar.undo())).toBe(true)
  await expect(editor(page).locator('a')).toHaveCount(0)
  expect(await page.evaluate(() => window.toolbar.text())).toBe('XHello world')
})

test('existing links can be retargeted and removed without deleting text', async ({ page }) => {
  await mount(page)
  await link(page)
  await page.getByLabel('Adresse', { exact: true }).fill('/first')
  await page.getByRole('button', { name: 'Übernehmen' }).click()
  await link(page)
  await expect(page.getByLabel('Adresse', { exact: true })).toHaveValue('/first')
  await page.getByLabel('Adresse', { exact: true }).fill('/second')
  await page.getByRole('button', { name: 'Übernehmen' }).click()
  await expect(editor(page).locator('a')).toHaveAttribute('href', '/second')
  await link(page)
  await page.getByRole('button', { name: 'Link entfernen' }).click()
  await expect(editor(page).locator('a')).toHaveCount(0)
  expect(await page.evaluate(() => window.toolbar.text())).toBe('Hello world')
})

for (const kind of ['removed', 'expired', 'replaced', 'history', 'invalidated']) {
  test(`${kind} dialog target cannot insert into a fallback position`, async ({ page }) => {
    await mount(page)
    if (kind === 'replaced' || kind === 'history') await page.evaluate(() => window.toolbar.edit())
    await link(page)
    await page.evaluate(kind => {
      if (kind === 'removed') window.toolbar.removeTarget()
      if (kind === 'expired') window.toolbar.edit(80)
      if (kind === 'replaced') window.toolbar.replaceDocument()
      if (kind === 'history') window.toolbar.undo()
      if (kind === 'invalidated') window.toolbar.invalidate()
    }, kind)
    const before = await page.evaluate(() => window.toolbar.text())
    await page.getByLabel('Adresse', { exact: true }).fill('/invalid-target')
    await page.getByRole('button', { name: 'Übernehmen' }).click()
    await expect(page.getByRole('alert')).not.toBeEmpty()
    await expect(editor(page).locator('a')).toHaveCount(0)
    expect(await page.evaluate(() => window.toolbar.text())).toBe(before)
  })
}

