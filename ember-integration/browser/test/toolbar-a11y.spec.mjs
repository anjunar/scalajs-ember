test('application file callback uses the actual chooser and P26 multipart service', async ({ page }) => {
  await mount(page)
  await action(page, 'image').click()
  await page.getByLabel('Alternativtext', { exact: false }).fill('Uploaded picture')
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Datei auswählen' }).click()
  await (await chooser).setFiles({ name: 'image.png', mimeType: 'image/png', buffer: fixturePng })
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(editor(page).locator('img')).toHaveAttribute('alt', 'Uploaded picture')
  await expect(editor(page).locator('img')).toHaveAttribute('src', /\/media\/assets\/[a-f0-9]{64}\.png/)
  await expect(page.getByRole('status')).toHaveText('Bild eingefügt.')
})

test('an existing image exposes its alt and can be made decorative without reinserting it', async ({ page }) => {
  await mount(page, 2, 2)
  await action(page, 'image').click()
  await page.getByLabel('Bildadresse', { exact: true }).fill('/media/assets/fixture.png')
  await page.getByLabel('Alternativtext', { exact: false }).fill('Before')
  await page.getByRole('button', { name: 'Übernehmen' }).click()
  const before = await editor(page).locator('img').evaluate(el => el.outerHTML)
  await page.evaluate(() => window.toolbar.selectImage())
  await action(page, 'image').click()
  await expect(page.getByRole('dialog')).toHaveAccessibleName('Bild bearbeiten')
  await expect(page.getByLabel('Alternativtext', { exact: false })).toHaveValue('Before')
  await page.getByLabel('Alternativtext', { exact: false }).fill('')
  await page.getByRole('button', { name: 'Übernehmen' }).click()
  await expect(editor(page).locator('img')).toHaveAttribute('alt', '')
  await expect(editor(page).locator('img')).toHaveCount(1)
  expect(await page.evaluate(() => window.toolbar.undo())).toBe(true)
  expect(await editor(page).locator('img').evaluate(el => el.outerHTML)).toBe(before)
})

test('composition availability disables and re-enables toolbar actions', async ({ page }) => {
  await mount(page, 2, 2)
  await page.evaluate(() => document.getElementById('toolbar-editor').dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true })))
  await expect(action(page, 'bold')).toBeDisabled()
  await expect(action(page, 'image')).toBeDisabled()
  await page.evaluate(() => document.getElementById('toolbar-editor').dispatchEvent(new CompositionEvent('compositionend', { bubbles: true })))
  await expect(action(page, 'bold')).toBeEnabled()
  await expect(action(page, 'image')).toBeEnabled()
})

test('readonly disables commands and rejects an already-open dialog', async ({ page }) => {
  await mount(page)
  await link(page)
  await page.evaluate(() => window.toolbar.readonly(true))
  await page.getByLabel('Adresse', { exact: true }).fill('/readonly')
  await page.getByRole('button', { name: 'Übernehmen' }).click()
  await expect(page.getByRole('alert')).toContainText('nicht bearbeitbar')
  await page.getByRole('button', { name: 'Abbrechen' }).click()
  for (const id of ['bold', 'italic', 'undo', 'redo', 'link', 'image']) await expect(action(page, id)).toBeDisabled()
  expect(await page.evaluate(() => window.toolbar.openLink())).toBe(false)
  expect(await page.evaluate(() => window.toolbar.text())).toBe('Hello world')
})

