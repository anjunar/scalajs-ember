import { test, expect } from '@playwright/test'
import { fixturePng } from '../media-server.mjs'

const editor = page => page.locator('#toolbar-editor')
const action = (page, id) => page.locator(`[data-command="${id}"]`)
async function mount(page, a = 0, b = 5) {
  await page.goto('/toolbar')
  await page.waitForFunction(() => window.ready)
  await editor(page).focus()
  await page.evaluate(([a, b]) => window.toolbar.select(a, b), [a, b])
}
async function link(page) {
  await action(page, 'link').click()
  await expect(page.getByRole('dialog')).toBeVisible()
}
test.afterEach(async ({ page }) => page.evaluate(() => window.toolbar?.dispose()).catch(() => {}))

test('named toolbar exposes pressed and disabled states and a single Tab stop', async ({ page }, testInfo) => {
  await mount(page)
  await expect(page.getByRole('toolbar', { name: 'Text bearbeiten' })).toBeVisible()
  await expect(action(page, 'bold')).toHaveAccessibleName('Fett')
  await expect(action(page, 'bold')).toHaveAttribute('aria-pressed', 'false')
  await expect(action(page, 'undo')).toBeDisabled()
  await expect(action(page, 'redo')).toBeDisabled()
  await expect(page.locator('[role="toolbar"] button[tabindex="0"]')).toHaveCount(1)
  await expect(editor(page)).toHaveAccessibleName('Dokument')
  await page.screenshot({ path: testInfo.outputPath('toolbar.png'), fullPage: true })
})

test('toolbar and modal remain usable on a narrow viewport', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await mount(page)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await link(page)
  await expect(page.getByLabel('Adresse', { exact: true })).toBeFocused()
  const box = await page.getByRole('dialog').boundingBox()
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: testInfo.outputPath('dialog-narrow.png'), fullPage: true })
})

test('mouse formatting retains editor focus and the selected text', async ({ page }) => {
  await mount(page)
  await action(page, 'bold').click()
  await expect(editor(page)).toBeFocused()
  await expect(editor(page).locator('strong')).toHaveText('Hello')
  await expect(action(page, 'bold')).toHaveAttribute('aria-pressed', 'true')
  await expect(action(page, 'undo')).toBeEnabled()
  await action(page, 'undo').click()
  await expect(editor(page).locator('strong')).toHaveCount(0)
  await expect(action(page, 'redo')).toBeEnabled()
})

test('Tab leaves the editor; arrows skip disabled actions; Space retains toolbar focus', async ({ page }) => {
  await mount(page)
  await page.keyboard.press('Tab')
  await expect(action(page, 'bold')).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(action(page, 'italic')).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(action(page, 'link')).toBeFocused()
  await page.keyboard.press('Home')
  await page.keyboard.press('Space')
  await expect(action(page, 'bold')).toBeFocused()
  await expect(editor(page).locator('strong')).toHaveText('Hello')
  await page.keyboard.press('End')
  await expect(action(page, 'image')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.locator('#readonly')).toBeFocused()
})

